#include "libft.h"

int	ft_atoi(const char *s)
{
	int	y;
	int	sign;
	int	i;

	y = 0;
	sign = 1;
	i = 0;
	while (s[i] == ' ' || (s[i] >= 9 && s[i] <= 13))
		i++;
	if (s[i] == '-' || s[i] == '+')
	{
		if (s[i] == '-')
			sign = -1;
		i++;
	}
	while (s[i] >= '0' && s[i] <= '9')
	{
		y = y * 10 + (s[i] - '0');
		i++;
	}
	return (y * sign);
}
